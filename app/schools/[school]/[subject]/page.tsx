function replaceSchoolInDetail(value: any, schoolName: string): any {
  if (typeof value === "string") return value.replaceAll("대원외고", schoolName).replaceAll("Daewon Foreign Language High School", schoolName + " Foreign Language High School");
  if (Array.isArray(value)) return value.map((item) => replaceSchoolInDetail(item, schoolName));
  if (value && typeof value === "object") return Object.fromEntries(Object.entries(value).map(([key, item]) => [key, replaceSchoolInDetail(item, schoolName)]));
  return value;
}

